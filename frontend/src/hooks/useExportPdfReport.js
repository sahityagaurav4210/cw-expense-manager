import { useState, useEffect, useCallback, useMemo } from "react";
import dayjs from "dayjs";
import {
  getStatementPreviewApi,
  downloadStatementPdfApi,
} from "../services/reports.service";
import { useUI } from "../context/UIContext";

/**
 * Generates month selection options (past 24 months + next 6 months).
 */
const generateMonthOptions = () => {
  const current = dayjs();
  const currentKey = current.format("YYYY-MM");
  const options = [];

  // 6 months in future to 24 months in past
  for (let i = 6; i >= -24; i--) {
    const d = current.add(i, "month");
    const key = d.format("YYYY-MM");
    const isCurrent = key === currentKey;
    options.push({
      label: isCurrent
        ? `${d.format("MMMM YYYY")} (Current Month)`
        : d.format("MMMM YYYY"),
      value: key,
      isCurrent,
    });
  }
  return options;
};

/**
 * Custom hook to manage month selection via Autocomplete,
 * loads the rendered HTML preview from the backend stream,
 * and handles downloading the PDF generated by the backend.
 */
export const useExportPdfReport = () => {
  const { showAlert } = useUI();
  const monthOptions = useMemo(() => generateMonthOptions(), []);

  // Default to current month option
  const defaultOption = useMemo(
    () => monthOptions.find((o) => o.isCurrent) || monthOptions[6],
    [monthOptions]
  );

  const [selectedOption, setSelectedOption] = useState(defaultOption);
  const [htmlReport, setHtmlReport] = useState("");
  const [loading, setLoading] = useState(false);
  const [downloading, setDownloading] = useState(false);

  // Fetch rendered HTML preview stream from backend
  const fetchPreview = useCallback(
    async (monthKey) => {
      setLoading(true);
      try {
        const html = await getStatementPreviewApi(monthKey);
        setHtmlReport(html);
      } catch (err) {
        showAlert(
          err.response?.data?.message ||
            err.message ||
            "Failed to load statement preview from server.",
          "error"
        );
      } finally {
        setLoading(false);
      }
    },
    [showAlert]
  );

  // Fetch preview when selected month changes
  useEffect(() => {
    if (selectedOption?.value) {
      fetchPreview(selectedOption.value);
    }
  }, [selectedOption, fetchPreview]);

  // Handle month selection change
  const handleMonthChange = (event, newOption) => {
    if (newOption) {
      setSelectedOption(newOption);
    }
  };

  // Download PDF generated and streamed from backend
  const handleDownloadPdf = async () => {
    if (!selectedOption?.value || downloading) return;
    setDownloading(true);
    try {
      const response = await downloadStatementPdfApi(selectedOption.value);
      const blob = new Blob([response.data], {
        type: response.headers["content-type"] || "application/pdf",
      });

      // Extract filename from header or build fallback
      let filename = `CW-Financial-Statement-${selectedOption.value}.pdf`;
      const disposition = response.headers["content-disposition"];
      if (disposition && disposition.indexOf("filename=") !== -1) {
        const matches = /filename[^;=\n]*=((['"]).*?\2|[^;\n]*)/.exec(disposition);
        if (matches != null && matches[1]) {
          filename = matches[1].replace(/['"]/g, "");
        }
      }

      const downloadUrl = window.URL.createObjectURL(blob);
      const link = document.createElement("a");
      link.href = downloadUrl;
      link.download = filename;
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      setTimeout(() => window.URL.revokeObjectURL(downloadUrl), 1000);

      showAlert(`Downloaded "${filename}" successfully.`, "success");
    } catch (err) {
      showAlert(
        err.response?.data?.message ||
          err.message ||
          "Failed to download PDF from server.",
        "error"
      );
    } finally {
      setDownloading(false);
    }
  };

  return {
    monthOptions,
    selectedOption,
    handleMonthChange,
    htmlReport,
    loading,
    downloading,
    handleDownloadPdf,
    refetchPreview: () => fetchPreview(selectedOption.value),
  };
};
